/// Key material dispersed as internal constants.
const KM0: u64 = 0x7A3F_E821_4D6B_C095;
const KM1: u64 = 0x1E8C_F432_9A5D_B067;
const KM2: u64 = 0x5C2A_8E19_F3D7_6B40;
const KM3: u64 = 0x9F61_D4A8_2B7E_C35F;

/// Derive a 32-byte key from scattered constants via S-box mixing.
fn derive_key() -> [u8; 32] {
    let s = [KM0, KM1, KM2, KM3];
    let mut k = [0u8; 32];
    for i in 0..32 {
        let raw = ((s[i % 4] >> ((i % 8) * 8)) & 0xFF) as u8;
        k[i] = SBOX[raw.wrapping_add(i as u8) as usize];
    }
    k
}

/// Encode plaintext to obfuscated bytes (used only for generation).
#[cfg(test)]
fn encode(text: &str) -> Vec<u8> {
    let key = derive_key();
    text.as_bytes()
        .iter()
        .enumerate()
        .map(|(i, &b)| {
            let mixed = b.wrapping_add((i as u8).wrapping_mul(0x5B));
            let substituted = SBOX[mixed as usize];
            substituted ^ key[i % 32]
        })
        .collect()
}

/// Decode obfuscated bytes back to plaintext at runtime.
fn decode(data: &[u8]) -> String {
    let key = derive_key();
    let bytes: Vec<u8> = data
        .iter()
        .enumerate()
        .map(|(i, &b)| {
            let unxored = b ^ key[i % 32];
            let unsubstituted = INV_SBOX[unxored as usize];
            unsubstituted.wrapping_sub((i as u8).wrapping_mul(0x5B))
        })
        .collect();
    String::from_utf8(bytes).unwrap_or_default()
}

